console.log(`// === 性能指标 ===`);
console.log(`// 原始方案: ${FILTER_TAPS} 次乘法/输入样本 × 3 输入/输出 = ${FILTER_TAPS * 3} 次乘法/输出`);
console.log(`// Polyphase: ~${branches[0].length} 次乘法/输出 (节省 ${(FILTER_TAPS * 3 / branches[0].length).toFixed(1)}x)`);
console.log(`// 旁瓣衰减: ~60dB`);
console.log(`// 过渡带: 7600Hz - 8400Hz (5%)`);

// 验证: 直流增益
let dcGain = 0;
for (let p = 0; p < DOWNSAMPLE_FACTOR; p++) {
  for (let k = 0; k < branches[p].length; k++) {
    dcGain += branches[p][k];
  }
}
