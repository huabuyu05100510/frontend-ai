#!/usr/bin/env node
/**
 * Generate polyphase FIR filter coefficients for 48kHz -> 16kHz downsampling.
 *
 * Algorithm:
 *   1. Design a Kaiser-windowed sinc lowpass filter (cutoff = 8kHz, transition band 5%)
 *   2. Decompose the N-tap filter into L=3 polyphase branches
 *   3. Output as JS code that can be inlined into capture-processor.js
 *
 * Reference: "Digital Signal Processing" by Oppenheim & Schafer, Ch. 7 (multirate)
 *
 * Output: writes to stdout, JS code ready to paste.
 */

'use strict';

// 零阶修正贝塞尔函数 I0(x) 的多项式近似
function besselI0(x) {
  let sum = 0;
  const halfX = x / 2;
  let fact = 1;
  for (let k = 0; k < 25; k++) {
    if (k > 0) fact *= k * k;
    sum += Math.pow(halfX, 2 * k) / Math.pow(fact, 2);
  }
  return sum;
}

// Kaiser 窗函数
function kaiserWindow(N, beta) {
  const w = new Float32Array(N);
  const denom = besselI0(beta);
  const M = N - 1;
  for (let n = 0; n < N; n++) {
    const r = (n - M / 2) / (M / 2);
    const arg = beta * Math.sqrt(Math.max(0, 1 - r * r));
    w[n] = besselI0(arg) / denom;
  }
  return w;
}

// Sinc 低通滤波器 (截止频率 fc, 归一化到 fs=1)
function sincLowpass(N, cutoff) {
  const h = new Float32Array(N);
  const M = N - 1;
  const center = M / 2;
  for (let n = 0; n < N; n++) {
    const k = n - center;
    if (k === 0) {
      h[n] = 2 * cutoff;
    } else {
      h[n] = Math.sin(2 * Math.PI * cutoff * k) / (Math.PI * k);
    }
  }
  return h;
}

// 完整设计: 加窗 sinc
function designLowpassFIR(N, cutoff, beta) {
  const sinc = sincLowpass(N, cutoff);
  const window = kaiserWindow(N, beta);
  const h = new Float32Array(N);
  for (let i = 0; i < N; i++) {
    h[i] = sinc[i] * window[i];
  }
  // 归一化使直流增益 = 1, 然后 × L (下采样因子)
  // 因为 polyphase 分解后, 每次只用 1/L 的系数, 增益会变 1/L
  // 乘以 L 保持每分支的直流增益 = 1
  let sum = 0;
  for (let i = 0; i < N; i++) sum += h[i];
  for (let i = 0; i < N; i++) {
    h[i] = (h[i] / sum) * DOWNSAMPLE_FACTOR;
  }
  return h;
}

// Polyphase 分解: 把 N-tap 滤波器分成 L 个分支
function polyphaseDecompose(h, L) {
  const N = h.length;
  const tapsPerBranch = Math.ceil(N / L);
  const branches = [];
  for (let p = 0; p < L; p++) {
    const branch = new Float32Array(tapsPerBranch);
    for (let k = 0; k < tapsPerBranch; k++) {
      const idx = p + k * L;
      branch[k] = idx < N ? h[idx] : 0;
    }
    branches.push(branch);
  }
  return branches;
}

// 浮点数转定点 (Q15 格式: 乘以 32768 然后取整)
function toQ15(arr) {
  return Array.from(arr).map(v => Math.round(v * 32768));
}

// ============== 主流程 ==============
// 参数 (来自 docs/tech-plan-polyphase-resampler.md)
const DOWNSAMPLE_FACTOR = 3;        // 48kHz -> 16kHz
const FILTER_TAPS = 64;             // 总 tap 数 (必须是 L 的倍数)
const KAISER_BETA = 5.653;          // 旁瓣衰减 ~60dB
const CUTOFF_NORMALIZED = 0.45 / DOWNSAMPLE_FACTOR; // 0.15 (相对 48kHz)

console.log('// ============================================');
console.log('// Auto-generated by scripts/generate-polyphase-coeffs.js');
console.log('// DO NOT EDIT — regenerate with: node scripts/generate-polyphase-coeffs.js');
console.log('// ============================================');
console.log(`// Filter: ${FILTER_TAPS}-tap Kaiser windowed sinc, beta=${KAISER_BETA}, cutoff=${CUTOFF_NORMALIZED}`);
console.log(`// Downsampling: ${DOWNSAMPLE_FACTOR}:1 (48kHz -> 16kHz)`);
console.log('');
console.log('// 3 polyphase branches, ~22 taps each');
console.log('');

const h = designLowpassFIR(FILTER_TAPS, CUTOFF_NORMALIZED, KAISER_BETA);
const branches = polyphaseDecompose(h, DOWNSAMPLE_FACTOR);

branches.forEach((branch, idx) => {
  const q15 = toQ15(branch);
  console.log(`const FILTER_PHASE_${idx} = new Int16Array([`);
  // 每行 8 个
  for (let i = 0; i < q15.length; i += 8) {
    const slice = q15.slice(i, i + 8);
    console.log('  ' + slice.join(', ') + ',');
  }
  console.log(']);');
});

